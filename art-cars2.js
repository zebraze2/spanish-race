function siren(x, y, o) { // flashing light bar
  const on = Math.floor((o.t || 0) * 6) % 2 === 0;
  P([x - 16, y, x + 16, y, x + 16, y - 4, x - 16, y - 4], '#3a2a22');
  P([x - 15, y - 4, x - 1, y - 4, x - 3, y - 12, x - 13, y - 12], on ? '#ff3b30' : '#9b2a24');
  P([x + 1, y - 4, x + 15, y - 4, x + 13, y - 12, x + 3, y - 12], on ? '#22409a' : '#3f9bff');
}
function star5(x, y, r, c) {
  const pts = [];
  for (let k = 0; k < 10; k++) { const rr = k % 2 ? r * 0.45 : r, a = -Math.PI / 2 + k * Math.PI / 5; pts.push(x + Math.cos(a) * rr, y + Math.sin(a) * rr); }
  P(pts, c);
}
function checker(x0, x1, y, s) {
  for (let x = x0, k = 0; x < x1; x += s, k++) {
    P([x, y, x + s, y, x + s, y + s, x, y + s], k % 2 ? '#3a2a22' : '#ffffff');
    P([x, y + s, x + s, y + s, x + s, y + 2 * s, x, y + 2 * s], k % 2 ? '#ffffff' : '#3a2a22');
  }
}
function ladder(x1, y1, x2, y2) {
  for (const dy of [-10, 0]) P([x1, y1 + dy, x2, y2 + dy, x2, y2 + dy + 4, x1, y1 + dy + 4], '#d5d9df');
  const n = Math.round(Math.hypot(x2 - x1, y2 - y1) / 14);
  for (let k = 1; k < n; k++) {
    const x = x1 + (x2 - x1) * k / n, y = y1 + (y2 - y1) * k / n;
    P([x - 1.5, y - 8, x + 1.5, y - 8, x + 1.5, y + 2, x - 1.5, y + 2], '#aab2bc');
  }
}
